#!/usr/bin/env node
/*
 * scope-foundation-css.js — build a scoped copy of Foundation 5 for the Sb4 app.
 *
 *   node scripts/scope-foundation-css.js \
 *       dashboard/apps/sb4.fma/css/foundation.css \
 *       dashboard/apps/sb4.fma/css/foundation-scoped.css
 *
 * Why: the Sb4 command panel (menu bar, command line, fill-in sheet, Motion
 * Pad) is built on Foundation 5, whose stylesheet restyles every bare
 * <input>, <label>, <button>, <table> and heading on the page. The rest of
 * the Sb4 page is now the card layout taken from the tool_status app, which
 * relies on browser defaults for those elements. Prefixing every Foundation
 * selector with `.sb4-scope` confines Foundation to the wrappers that carry
 * that class.
 *
 * Rules:
 *   html ...            dropped (root font-size stays the browser's)
 *   body ...            -> .sb4-scope (minus background/position/margin/padding,
 *                          so the wrapper is transparent and NOT a positioning
 *                          root: Foundation's reveal modals are absolutely
 *                          positioned against the document)
 *   * / *:before/after  -> .sb4-scope * ...
 *   meta.foundation-*   left as-is (Foundation JS reads them from <head>)
 *   .reveal-modal-bg    left as-is (Foundation JS appends it to <body>)
 *   everything else     -> .sb4-scope <selector>
 *   @keyframes / @font-face bodies are left alone.
 */
"use strict";

var fs = require("fs");
var postcss = require("postcss");

var SCOPE = ".sb4-scope";

function scopeSelector(sel) {
    sel = sel.trim();
    if (!sel) return null;
    if (/^meta\.foundation-/.test(sel)) return sel;
    if (/(^|[\s>+~])\.reveal-modal-bg(\b|$)/.test(sel)) return sel;
    if (/^html(\b|$)/.test(sel)) {
        // "html.lt-ie9 .x" style selectors: keep the descendant part, scoped
        var rest = sel.replace(/^html[^\s]*/, "").trim();
        return rest ? SCOPE + " " + rest : null;
    }
    if (/^body(\b|$)/.test(sel)) {
        // body.f-topbar-fixed -> .sb4-scope.f-topbar-fixed ; body .x -> .sb4-scope .x
        return sel.replace(/^body/, SCOPE);
    }
    if (/^\*/.test(sel)) return SCOPE + " " + sel;
    return SCOPE + " " + sel;
}

// Foundation's reveal plugin re-parents an open modal to its root element.
// Sb4 points that root at the .sb4-modals wrapper (index.html), and as a
// belt-and-braces each modal also carries the scope class itself, so
// selectors on the modal element get a second, self-scoped form.
function scopeSelectors(sel) {
    var out = [scopeSelector(sel)];
    if (/^\.reveal-modal(?!-bg)/.test(sel.trim())) {
        out.push(sel.trim().replace(/^\.reveal-modal/, SCOPE + ".reveal-modal"));
    }
    return out;
}

var BODY_STRIP = {
    background: true,
    "background-color": true,
    position: true,
    margin: true,
    padding: true,
    height: true,
};

function run(inFile, outFile) {
    var css = fs.readFileSync(inFile, "utf8");
    var root = postcss.parse(css);
    var dropped = 0;

    root.walkRules(function (rule) {
        var parent = rule.parent;
        if (parent && parent.type === "atrule" && /keyframes|font-face/.test(parent.name)) return;
        var wasBody = false;
        var out = [];
        rule.selectors.forEach(function (s) {
            if (/^body(\b|$)/.test(s.trim()) && !/\s/.test(s.trim())) wasBody = true;
            scopeSelectors(s).forEach(function (scoped) {
                if (scoped && out.indexOf(scoped) === -1) out.push(scoped);
            });
        });
        if (!out.length) {
            rule.remove();
            dropped++;
            return;
        }
        rule.selectors = out;
        if (wasBody) {
            rule.walkDecls(function (d) {
                if (BODY_STRIP[d.prop]) d.remove();
            });
        }
    });

    var header =
        "/* GENERATED by scripts/scope-foundation-css.js from " +
        inFile.replace(/^.*\//, "") +
        " — do not edit.\n" +
        "   Foundation 5.5.3 confined to elements under a .sb4-scope wrapper. */\n";
    fs.writeFileSync(outFile, header + root.toString());
    console.log("wrote " + outFile + " (" + dropped + " rules dropped)");
}

if (require.main === module) {
    var args = process.argv.slice(2);
    if (args.length !== 2) {
        console.error("usage: scope-foundation-css.js <in.css> <out.css>");
        process.exit(1);
    }
    run(args[0], args[1]);
}
